import React, { useState } from 'react';
import { X, Download, FileText, Printer, Check } from 'lucide-react';
import { api } from '../../services/api';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  activeSessionId: string | null;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  activeSessionId,
}) => {
  const [downloaded, setDownloaded] = useState<string | null>(null);

  if (!isOpen) return null;

  const exportMarkdown = async () => {
    try {
      let content = '# FinSta Conversation Log\n';
      content += `*Generated by FinSta - Your smart money sidekick*\n`;
      content += `*Date: ${new Date().toLocaleDateString()}*\n\n`;
      content += `---\n\n`;

      if (activeSessionId) {
        const session = await api.getSession(activeSessionId);
        content += `## ${session.title}\n\n`;
        session.messages.forEach((m) => {
          const role = m.sender === 'user' ? '👤 User' : '🤖 FinSta';
          content += `### ${role}\n${m.content}\n\n`;
        });
      } else {
        content += 'No active conversation.\n\n';
      }

      content += `---\n`;
      content += `*Disclaimer: FinSta provides educational information, not professional financial advice.*\n`;

      const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
      const url = URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `FinSta_Chat_${Date.now()}.md`);
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);

      setDownloaded('markdown');
      setTimeout(() => setDownloaded(null), 2000);
    } catch (e) {
      console.error(e);
    }
  };

  const exportPrintOrPdf = () => {
    window.print();
    setDownloaded('pdf');
    setTimeout(() => setDownloaded(null), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-[#24221F]/40 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="bg-background rounded-2xl shadow-warm border border-border w-full max-w-sm overflow-hidden">
        
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-border bg-surface">
          <div className="flex items-center gap-2">
            <Download className="w-5 h-5 text-primary" />
            <h3 className="font-semibold text-base text-primary">
              Export Conversation
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-text-muted hover:text-text hover:bg-background transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Options */}
        <div className="p-6 space-y-3 bg-background">
          <button
            onClick={exportMarkdown}
            className="w-full flex items-center justify-between p-3.5 rounded-xl border border-border bg-surface hover:bg-background text-left transition shadow-warm"
          >
            <div className="flex items-center gap-3">
              <div className="p-2 rounded-lg bg-background text-primary border border-border">
                <FileText className="w-5 h-5" />
              </div>
              <div>
                <span className="text-xs font-semibold text-text block">
                  Export as Markdown (.md)
                </span>
                <span className="text-[11px] text-text-muted">
                  Clean markdown formatted log
                </span>
              </div>
            </div>
            {downloaded === 'markdown' && <Check className="w-4 h-4 text-primary" />}
          </button>

          <button
            onClick={exportPrintOrPdf}
            className="w-full flex items-center justify-between p-3.5 rounded-xl border border-border bg-surface hover:bg-background text-left transition shadow-warm"
          >
            <div className="flex items-center gap-3">
              <div className="p-2 rounded-lg bg-background text-accent border border-border">
                <Printer className="w-5 h-5" />
              </div>
              <div>
                <span className="text-xs font-semibold text-text block">
                  Print or Save as PDF
                </span>
                <span className="text-[11px] text-text-muted">
                  Standard browser PDF printer
                </span>
              </div>
            </div>
            {downloaded === 'pdf' && <Check className="w-4 h-4 text-primary" />}
          </button>
        </div>

      </div>
    </div>
  );
};
